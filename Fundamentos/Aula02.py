# ============================================
# Exercício - Soma de dois números
# Objetivo: Praticar entrada de dados, uso de
# variáveis, operações matemáticas e f-strings.
# ============================================

# Solicita ao usuário o primeiro número inteiro.
numero1 = int(input("Digite um número: "))

# Solicita ao usuário o segundo número inteiro.
numero2 = int(input("Digite outro número: "))

# Realiza a soma dos dois valores informados.
soma = numero1 + numero2

# Exibe a operação e o resultado da soma.
print(f"A soma {numero1} + {numero2} = {soma}")